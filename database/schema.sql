-- InternLink — PostgreSQL schema (PostgreSQL 12+)
--
-- Run with either:
--   npm run db:setup                                   (creates the database too)
--   psql -U postgres -d internlink -f database/schema.sql -f database/seed.sql
--
-- WARNING: this script drops and recreates every InternLink table.

DROP TABLE IF EXISTS notifications, applications, jobs, announcements,
                     categories, employers, students, users CASCADE;

-- ---------------------------------------------------------------- users ---
-- ENUM columns from MySQL are TEXT + CHECK constraints: easy to alter later and
-- they never raise "invalid input value for enum" on a plain SELECT.
CREATE TABLE users (
  id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role          TEXT         NOT NULL CHECK (role IN ('student','employer','admin')),
  email         VARCHAR(150) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  first_name    VARCHAR(80)  NOT NULL,
  last_name     VARCHAR(80)  NOT NULL,
  status        TEXT         NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive','pending')),
  created_at    TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);
-- MySQL's default collation made email lookups case-insensitive; keep that behaviour.
CREATE UNIQUE INDEX users_email_lower_key ON users (LOWER(email));

-- ------------------------------------------------------------- students ---
CREATE TABLE students (
  id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     INT          NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
  student_no  VARCHAR(50)  UNIQUE,
  course      VARCHAR(120) DEFAULT '',
  year_level  VARCHAR(50)  DEFAULT '',
  phone       VARCHAR(40)  DEFAULT '',
  address     VARCHAR(255) DEFAULT '',
  bio         TEXT,
  skills      TEXT,
  resume_path VARCHAR(255)
);

-- ------------------------------------------------------------ employers ---
CREATE TABLE employers (
  id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id         INT          NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
  company_name    VARCHAR(150) NOT NULL,
  description     TEXT,
  location        VARCHAR(150) DEFAULT '',
  website         VARCHAR(255) DEFAULT '',
  logo_path       VARCHAR(255),
  approval_status TEXT         NOT NULL DEFAULT 'pending' CHECK (approval_status IN ('pending','approved','rejected'))
);

-- ----------------------------------------------------------- categories ---
CREATE TABLE categories (
  id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR(120) NOT NULL,
  description VARCHAR(255) DEFAULT ''
);
CREATE UNIQUE INDEX categories_name_lower_key ON categories (LOWER(name));

-- ----------------------------------------------------------------- jobs ---
CREATE TABLE jobs (
  id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employer_id INT          NOT NULL REFERENCES employers(id) ON DELETE CASCADE,
  title       VARCHAR(160) NOT NULL,
  description TEXT         NOT NULL,
  location    VARCHAR(150) NOT NULL,
  course      VARCHAR(120) NOT NULL,
  type        TEXT         NOT NULL DEFAULT 'Internship' CHECK (type IN ('Internship','OJT','Part-time')),
  slots       INT          NOT NULL DEFAULT 1,
  deadline    DATE         NOT NULL,
  status      TEXT         NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','published','closed','rejected')),
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);
CREATE INDEX jobs_employer_idx       ON jobs (employer_id);
CREATE INDEX jobs_status_created_idx ON jobs (status, created_at DESC);

-- --------------------------------------------------------- applications ---
CREATE TABLE applications (
  id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_id       INT         NOT NULL REFERENCES jobs(id)     ON DELETE CASCADE,
  student_id   INT         NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  cover_letter TEXT,
  resume_path  VARCHAR(255),
  status       TEXT        NOT NULL DEFAULT 'submitted'
               CHECK (status IN ('submitted','reviewing','shortlisted','accepted','rejected')),
  applied_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT one_application UNIQUE (job_id, student_id)
);
-- PostgreSQL does not index foreign keys automatically.
CREATE INDEX applications_student_idx ON applications (student_id, applied_at DESC);

-- -------------------------------------------------------- notifications ---
-- is_read stays 0/1 (not BOOLEAN) so the JSON the React app receives is unchanged.
CREATE TABLE notifications (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INT          NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title      VARCHAR(160) NOT NULL,
  message    TEXT         NOT NULL,
  is_read    SMALLINT     NOT NULL DEFAULT 0 CHECK (is_read IN (0,1)),
  created_at TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);
CREATE INDEX notifications_user_idx ON notifications (user_id, created_at DESC);

-- --------------------------------------------------------- announcements ---
CREATE TABLE announcements (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title      VARCHAR(180) NOT NULL,
  content    TEXT         NOT NULL,
  audience   TEXT         NOT NULL DEFAULT 'all' CHECK (audience IN ('all','student','employer')),
  created_at TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);
